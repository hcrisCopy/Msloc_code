import json
import time
import os
import re
import argparse
from typing import List, Dict, Any, Tuple
from tqdm import tqdm
from zai import ZhipuAiClient
import random

random.seed(42)

SYSTEM_PROMPT = """

You are an experienced expert in text analysis and semantic evaluation. Your primary task is to assess the semantic alignment and quality difference between a single AI-generated "explanatory sentence (Text A)" and a list of "standard explanations (Text B)."

**Task: Evaluating an individual prediction against multiple ground truth descriptions:**
You must disregard the actual video content and rely solely on a comparison of the two texts. Find the **most relevant** description in Text B to evaluate Text A against. 

## Input Data 
- **[Text A] (Single Model Prediction)**: ONE anomaly explanation sentence generated by the model (may include the predicted anomaly type).
- **[Text B] (Ground Truth)**: A list of standard anomaly descriptions (each containing the actual anomaly type and detailed descriptions).

## Evaluation Dimensions & Scoring Criteria (Maximum 5 points per dimension) 

### 1. Text Coherence & Fluency 
- **5 points**: Sentence is smooth, grammatically correct, and logically sound.
- **4 points**: Minor grammatical errors or awkward phrasing, but fully comprehensible.
- **3 points**: Somewhat fragmented or repetitive, but still conveys the basic meaning.
- **1-2 points**: Illogical, meaningless, or severely fragmented making it difficult to read.

### 2. Anomalous Object Accuracy 
- **5 points**: Object in A exactly matches or refers to the core part of the corresponding object in B.
- **4 points**: Object in A is overly broad or slightly deviates but remains relevant.
- **3 points**: Loose connection to the object in B.
- **1-2 points**: Completely unrelated object or hallucinated object not in B.

### 3. Anomaly Type Accuracy 
- **5 points**: The anomaly type in A matches B, with core characteristics aligning perfectly.
- **4 points**: Recognized but described somewhat vaguely (e.g., "looks strange" or "quality degradation").
- **3 points**: Partially related anomaly type but misses the primary nature of the anomaly.
- **1-2 points**: Completely opposite or unrelated anomaly type.

### 4. Description Consistency & Detail Accuracy 
- **5 points**: Accurately describes the core details and pre/post-state changes matching B.
- **4 points**: Covers core details but omits specific state change directions, or includes minor redundant info.
- **3 points**: Generic description, lacking specific details present in B.
- **1-2 points**: Describes opposite changes, or contains severe hallucinations not supported by B.

## Score Calculation
Calculate the arithmetic average of the 4 dimensions (a number between 1.0 and 5.0).
Only output the final average score as a single number **without any additional explanation**. (e.g., 4.25)
"""

class CotEvaluator:
    def __init__(self, gt_path: str, pred_path: str, api_key: str, output_path: str, model_name: str):
        self.client = ZhipuAiClient(api_key=api_key)
        self.gt_data = self._load_json(gt_path)
        self.pred_data = self._load_json(pred_path)
        self.output_path = output_path
        self.model_name = model_name
        self.results = []
        # 加载已有的结果，支持断点续传
        self.processed_ids = self._load_existing_results()

    def _load_json(self, path: str) -> List[Dict]:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    def _load_existing_results(self) -> set:
        processed = set()
        if os.path.exists(self.output_path):
            with open(self.output_path, 'r', encoding='utf-8') as f:
                for line in f:
                    try:
                        item = json.loads(line)
                        # 使用 video_path + segment 作为唯一标识
                        key = f"{item['video_path']}_{item['segment_idx']}"
                        processed.add(key)
                    except json.JSONDecodeError:
                        continue
        print(f"已加载 {len(processed)} 条历史结果")
        return processed

    def format_cot_entries(self, cot_entries, source_label):
        parts = []
        for entry in cot_entries:

            obj_caption = entry.get("obj_caption") or entry.get("bnd_caption") or ""
            if not (obj_caption):
                continue
            segment = []
            if obj_caption:
                segment.append(f"{obj_caption}")
            parts.append(f"[{source_label}] " + "; ".join(segment))
        return parts
    
    def ensure_list(self, value):
        if isinstance(value, dict):
            return [value]
        if isinstance(value, list):
            return value
        return []

    def calculate_iou(self, seg1, seg2):
        """计算两个时间段的 IoU"""
        start1, end1 = seg1
        start2, end2 = seg2

        intersection_start = max(start1, start2)
        intersection_end = min(end1, end2)
        
        if intersection_end <= intersection_start:
            return 0.0

        intersection = intersection_end - intersection_start
        union = (end1 - start1) + (end2 - start2) - intersection
        
        if union <= 0:
            return 0.0
            
        return intersection / union

    def _call_llm_with_retry(self, system_prompt: str, user_prompt: str) -> str:
        MAX_RETRIES = 3
        RETRY_DELAY = 2
        for attempt in range(MAX_RETRIES):
            try:
                response = self.client.chat.completions.create(
                    model=self.model_name,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt}
                    ],
                    temperature=0.1 # 降低随机性
                )
                return response.choices[0].message.content
            except Exception as e:
                tqdm.write(f"API调用失败 (尝试 {attempt+1}/{MAX_RETRIES}): {e}")
                if attempt < MAX_RETRIES - 1:
                    time.sleep(RETRY_DELAY * (attempt + 1))
                else:
                    return "" # 失败返回空

    def _extract_cot_text(self, pred_anno: Dict) -> str:
        """提取预测文本并判断是否包含边界描述"""
        text = pred_anno.get('response', '')
        if not text:
             return ""
        return text

    def evaluate(self):
        # 建立 Pred 的索引，方便查找
        pred_map = {item.get('video_path', ''): item for item in self.pred_data}

        # 1. 预处理：收集所有待处理的任务（每个tool_domain下，随机抽取10个不同video_path，每个视频只评测第一个segment）
        print("正在统计任务总数...")
        domain_video_map = {}
        for gt_item in self.gt_data:
            video_path = gt_item.get('video_path', '')
            if not video_path:
                continue
            pred_item = pred_map.get(video_path)
            if not pred_item:
                continue
            if gt_item.get('type') != 'fake':
                continue
            if len(gt_item['annotations']) != len(pred_item['model_inference']['response']):
                continue
            # 只取第一个segment
            seg_idx = 0
            gt_anno = gt_item.get('annotations', [])[seg_idx] if gt_item.get('annotations', []) else None
            if gt_anno is None:
                continue
            task_key = f"{video_path}_{seg_idx}"
            if task_key in self.processed_ids:
                continue
            pred_segment = [0, 0]
            pred_text = ""
            if seg_idx < len(pred_item.get('model_inference', {}).get('segment', [])):
                pred_text = pred_item['model_inference']['response'][seg_idx]
                pred_segment = pred_item['model_inference']['segment'][seg_idx]
            else:
                print(f"Warning: Pred 中缺少对应的 annotation {task_key}")
            gt_segment = gt_anno.get('segment', [0, 0])
            iou = self.calculate_iou(gt_segment, pred_segment)
            if iou <= 0.7:
                continue
            cot_type = ""
            if gt_anno.get('segment_label', '').lower() == "real":
                cot_type = "Real"
            elif "Round4" in video_path:
                cot_type = "Spatio-Temporal Fake"
            else:
                cot_type = "Temporal Fake"
            obj_cot = self.ensure_list(gt_anno.get('obj_cot', []))
            bnd_cot_st = self.ensure_list(gt_anno.get('bnd_cot_st', []))
            bnd_cot_ed = self.ensure_list(gt_anno.get('bnd_cot_ed', []))
            all_cot_parts = []
            all_cot_parts.extend(o['obj_caption'] for o in obj_cot)
            if bnd_cot_st:
                all_cot_parts.extend(o['bnd_caption'] for o in bnd_cot_st)
            if bnd_cot_ed:
                all_cot_parts.extend(o['bnd_caption'] for o in bnd_cot_ed)
            gt_cot = f"{cot_type}\n" + "\n".join(all_cot_parts)
            if not gt_cot:
                continue
            gt_has_bnd = bool(bnd_cot_st or bnd_cot_ed)
            tool_domain = gt_anno.get('tool_domain', 'unknown')
            if tool_domain not in domain_video_map:
                domain_video_map[tool_domain] = []
            domain_video_map[tool_domain].append({
                'video_path': video_path,
                'seg_idx': seg_idx,
                'pred_text': pred_text,
                'gt_cot': gt_cot,
                'gt_has_bnd': gt_has_bnd,
                'iou': iou,
                'tool_domain': tool_domain
            })
        # 每类随机抽取10个不同video_path
        tasks = []
        for domain, video_tasks in domain_video_map.items():
            # 按video_path去重
            unique_map = {}
            for t in video_tasks:
                if t['video_path'] not in unique_map:
                    unique_map[t['video_path']] = t
            unique_tasks = list(unique_map.values())
            sample_size = min(len(unique_tasks), 10)
            sampled = random.sample(unique_tasks, sample_size)
            print(f"Domain '{domain}': sampled {sample_size}/{len(unique_tasks)}")
            tasks.extend(sampled)
        print(f"共找到 {len(tasks)} 个待评测任务 (每类最多10个视频，每视频1个segment)")
        if not tasks:
            return
        random.shuffle(tasks)
        # 2. 使用 tqdm 处理任务
        with open(self.output_path, 'a', encoding='utf-8') as f_out:
            pbar = tqdm(tasks, desc="评测进度")
            for task in pbar:
                video_path = task['video_path']
                seg_idx = task['seg_idx']
                pred_text = task['pred_text']
                gt_cot = task['gt_cot']
                gt_has_bnd = task['gt_has_bnd']
                iou = task['iou']
                if not pred_text:
                    record = {
                        "video_path": video_path,
                        "segment_idx": seg_idx,
                        "has_boundary": gt_has_bnd,
                        "gt_cot": gt_cot,
                        "pred_text": "",
                        "score": 0,
                        "reason": "预测内容为空",
                        "iou": 0,
                        "tool_domain": task['tool_domain']
                    }
                    f_out.write(json.dumps(record, ensure_ascii=False) + "\n")
                    f_out.flush()
                    continue
                
                # Split pred_text into lines to evaluate them individually
                raw_lines = [line.strip() for line in pred_text.split('\n') if line.strip()]
                
                category_label = ""
                pred_lines = []
                
                if raw_lines:
                    first_line_lower = raw_lines[0].lower()
                    if "forgery" in first_line_lower or "fake" in first_line_lower or "real" in first_line_lower:
                        category_label = raw_lines[0]
                        desc_lines = raw_lines[1:]
                    else:
                        desc_lines = raw_lines
                        
                    for line in desc_lines:
                        if len(line) > 5:
                            if category_label:
                                pred_lines.append(f"Predicted Type: {category_label} | Description: {line}")
                            else:
                                pred_lines.append(line)
                                
                    if not pred_lines and category_label:
                        pred_lines.append(f"Predicted Type: {category_label}")
                
                if not pred_lines:
                    record = {
                        "video_path": video_path,
                        "segment_idx": seg_idx,
                        "has_boundary": gt_has_bnd,
                        "gt_cot": gt_cot,
                        "pred_text": pred_text,
                        "score": 0,
                        "reason": "预测内容未包含有效描述",
                        "iou": 0,
                        "tool_domain": task['tool_domain']
                    }
                    f_out.write(json.dumps(record, ensure_ascii=False) + "\n")
                    f_out.flush()
                    continue

                system_prompt = SYSTEM_PROMPT
                scores = []
                for p_idx, pred_line in enumerate(pred_lines):
                    user_prompt = f"""
                        Text A (Single Model Prediction):
                        {pred_line}
                        
                        Text B (Ground Truth List):
                        {gt_cot}
                    """
                    result_str = self._call_llm_with_retry(system_prompt, user_prompt)
                    result_str = result_str.replace('\n', '') if '\n' in result_str else result_str 
                    try:
                        score = float(result_str.strip())
                        scores.append(score)
                    except ValueError:
                        print(f"Warning: Failed to parse score '{result_str}' from LLM. using 0")
                        scores.append(0.0)
                    time.sleep(0.5)

                final_score = sum(scores) / len(scores) if scores else 0.0

                record = {
                    "video_path": video_path,
                    "segment_idx": seg_idx,
                    "has_boundary": gt_has_bnd,
                    "gt_cot": gt_cot,
                    "pred_text": pred_text,
                    "iou": iou,
                    "score": final_score,
                    "tool_domain": task['tool_domain']
                }
                f_out.write(json.dumps(record, ensure_ascii=False) + "\n")
                f_out.flush()

    def print_summary(self):
        print("\n=== 评测完成，按tool_domain分类统计结果 ===")
        # 重新读取所有结果，按tool_domain分类统计平均分
        domain_score = {}
        domain_count = {}
        if os.path.exists(self.output_path):
            with open(self.output_path, 'r', encoding='utf-8') as f:
                for line in f:
                    try:
                        item = json.loads(line)
                        score = float(item['score'])
                        # 兼容老结果无tool_domain的情况
                        tool_domain = item.get('tool_domain')
                        if not tool_domain:
                            # 尝试从gt_cot中推断
                            tool_domain = 'unknown'
                        if tool_domain not in domain_score:
                            domain_score[tool_domain] = 0.0
                            domain_count[tool_domain] = 0
                        domain_score[tool_domain] += score
                        domain_count[tool_domain] += 1
                    except Exception as e:
                        pass
        total_score = 0
        total_count = 0
        for domain in domain_score:
            avg = domain_score[domain] / domain_count[domain] if domain_count[domain] else 0
            print(f"{domain}: 平均分 {avg:.2f} (共 {domain_count[domain]} 条)")
            total_score += domain_score[domain]
            total_count += domain_count[domain]
        if total_count > 0:
            print(f"总体平均分: {total_score / total_count:.2f} (共 {total_count} 条)")

